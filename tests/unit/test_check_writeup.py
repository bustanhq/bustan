def test_a_ticket_without_a_parent_fails_and_an_epic_does_not(
    writeup: ModuleType, monkeypatch: pytest.MonkeyPatch
) -> None:
    def fake_get(path: str) -> object:
        if path.endswith("/issues/284/parent"):
            raise writeup.check_ownership.GitHubError(f"GET {path} returned 404: Not Found")
        if path.endswith("/issues/262/parent"):
            return {"number": 197, "title": "Enforce the layer table"}
        raise AssertionError(path)

    monkeypatch.setattr(writeup.check_ownership, "_get", fake_get)

    assert writeup.check_parent("o/r", 284, epic=False).level == "FAIL"
    assert writeup.check_parent("o/r", 262, epic=False).detail.startswith("parent #197")
    assert writeup.check_parent("o/r", 284, epic=True).level == "ok"
