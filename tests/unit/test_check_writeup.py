def _load(name: str) -> ModuleType:
    if name in sys.modules:
        return sys.modules[name]
    module_spec = spec_from_file_location(name, SCRIPTS / f"{name}.py")
    assert module_spec is not None
    assert module_spec.loader is not None
    module = module_from_spec(module_spec)
    # Registered before execution so check_writeup's own `import check_ownership`
    # resolves to the copy loaded here rather than searching sys.path for one.
    sys.modules[name] = module
    module_spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def writeup() -> ModuleType:
    _load("check_ownership")
    return _load("check_writeup")


def _failing(findings: list[Any]) -> set[str]:
    return {finding.check for finding in findings if finding.level == "FAIL"}


